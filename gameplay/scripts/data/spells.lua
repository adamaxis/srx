local DRAIN_LEVEL_BASE = { [0] = 1, [1] = 3, [2] = 6, [3] = 10 }   -- -(s8)0x166AD4[i] [C]

function Spell:is_damaging() return self.damage_class ~= 0xFF end   -- [H]
-- First half of 0x10660 [C]: returns (drain base, drain target number).
-- The second half (subtracting the caster stat term from 0x55F02/0x55F20 and +0x7C) is a C++/actor-field
-- input and is passed in by the caller as stat_reduction (0x106BC..0x106D6), already halved.
function Spell:drain(force, stat_reduction)
    local target = ((force >> 1) + (force & 1)) + self.drain_modifier
    if target < 2 then target = 2 end
    return DRAIN_LEVEL_BASE[self.drain_level] - (stat_reduction or 0), target
end
function Spell:item_id() return E.SPELL_ITEM_BASE + self.type end

