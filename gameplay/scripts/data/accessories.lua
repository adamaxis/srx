-- data/accessories.lua: one record per weapon accessory, merging every ROM table that describes accessories.
-- Sources [C]:
--   id / bit       : +0x6E[weapon slot] bit (1 << id), set at 0x5719C (Laser bit cleared when buying Smartgun, 0x571AA)
--   name           : 0x1AAE07.. (6 strings, 0x80 = line break, 0xFF end; previously cited as 0x1AAE0C)
--   price_by_shop  : u16 at 0x1AAE8C + shop*0x0C + id*2, read at 0x58628 (FFF0B6 = shop 0..2 sell accessories),
--                    then adjusted by 0x57A6E into FFF0BE, which 0x5717E subtracts from FFFBFE money.
--                    (0x5703E also builds a 0x10-stride pointer into this table; it is never read - dead.)
--   fit rules      : Weapon:can_fit (0x5709E..0x57108, refusal texts 0x1AA65C/683/6B2/6E4)
--   TN delta       : Weapon:tn_modifier (0x556C6)
-- Generated by tools/gen_records.py accessories.
local E = require("enums")
local Accessory = E.Accessory

---@class AccessoryRec
local AccessoryRec = {}
AccessoryRec.__index = AccessoryRec
setmetatable(AccessoryRec, { __call = function(_, t) return setmetatable(t, AccessoryRec) end })

function AccessoryRec:bit() return 1 << self.id end
function AccessoryRec:fitted(bits) return (bits & self:bit()) ~= 0 end
function AccessoryRec:base_price(shop) return self.price_by_shop[shop] end
-- Buying applies the bit; buying a Smartgun also clears an installed Laser Sight (0x571A0..0x571AA) [C]
function AccessoryRec:apply(bits)
    bits = bits | self:bit()
    if self.id == Accessory.SMARTGUN then bits = bits & ~(1 << Accessory.LASER_SIGHT) end
    return bits & 0xFF
end

