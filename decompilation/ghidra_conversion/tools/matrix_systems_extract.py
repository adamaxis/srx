#!/usr/bin/env python3
"""Extract typed Matrix system data from the US Genesis ROM.

The ROM stores 25 Matrix maps at 0x15DB48. Each entry points to a 14x10 map
and a linked node-record block. This is an offline content import; the Qt game
loads the generated Lua data and never reads ROM addresses at runtime.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROM_TABLE = 0x15DB48
MAP_CELLS = 14 * 10
NODE_BYTES = 0x14
SYSTEM_COUNT = 25
FILE_CLASS_TABLE = 0xE4060
FILE_CLASS_COUNT = 47
FILE_CLASS_STRIDE = 16
PROGRAM_STATE_TABLE = 0xE2FBE
PROGRAM_STATE_COUNT = 16
PROGRAM_STATE_STRIDE = 14
ALERT_STATE_TABLE = 0xE3074
ALERT_STATE_COUNT = 3
ALERT_STATE_STRIDE = 14
NODE_FUNCTION_TABLE = 0xE309E
NODE_FUNCTION_COUNT = 6
NODE_FUNCTION_STRIDE = 4
SECURITY_BAND_TABLE = 0xE30B6
SECURITY_BAND_COUNT = 5
SECURITY_BAND_STRIDE = 8
IC_RATING_COLUMN_TABLE = 0xE30DE
IC_TYPE_TABLE = 0xE30E7
IC_TYPE_COUNT = 9
IC_TYPE_STRIDE = 16
IC_VISIBILITY_TABLE = 0xE3177
IC_VISIBILITY_COUNT = 3
IC_VISIBILITY_STRIDE = 16


def read_u32(data: bytes, offset: int) -> int:
    return int.from_bytes(data[offset : offset + 4], "big")


def signed_byte(value: int) -> int:
    return value - 0x100 if value >= 0x80 else value


def require_range(data: bytes, start: int, size: int, label: str) -> None:
    if start < 0 or size < 0 or start + size > len(data):
        raise ValueError(
            f"{label} range 0x{start:X}..0x{start + size:X} is outside the ROM"
        )


def system_records(data: bytes) -> list[dict[str, object]]:
    systems: list[dict[str, object]] = []
    for system_id in range(SYSTEM_COUNT):
        entry = ROM_TABLE + system_id * 8
        map_offset = read_u32(data, entry)
        node_offset = read_u32(data, entry + 4)
        next_node_offset = (
            read_u32(data, entry + 12)
            if system_id + 1 < SYSTEM_COUNT
            else node_offset + 0x280
        )
        if not (0x100000 <= map_offset < len(data)):
            raise ValueError(
                f"system {system_id} has invalid map pointer 0x{map_offset:X}"
            )
        if not (0x100000 <= node_offset < len(data)):
            raise ValueError(
                f"system {system_id} has invalid node pointer 0x{node_offset:X}"
            )
        if next_node_offset < node_offset:
            raise ValueError(f"system {system_id} node range runs backwards")

        require_range(data, map_offset, MAP_CELLS, f"system {system_id} map")
        max_records = min(32, (next_node_offset - node_offset) // NODE_BYTES)
        require_range(
            data,
            node_offset,
            max_records * NODE_BYTES,
            f"system {system_id} nodes",
        )

        nodes: dict[int, dict[str, object]] = {}
        for node_id in range(max_records):
            record_offset = node_offset + node_id * NODE_BYTES
            record = data[record_offset : record_offset + NODE_BYTES]
            function_id = record[0]
            if function_id == 0xFF or function_id > 5:
                continue
            nodes[node_id] = {
                "function_id": function_id,
                "file_class_id": record[1],
                "x": record[3],
                "y": record[4],
                "security_color": record[5],
                "security": record[6],
                "links": {
                    link_id: signed_byte(value)
                    for link_id, value in enumerate(record[7:15])
                },
                "ic_condition": signed_byte(record[0x0F]),
                "ic_reaction": signed_byte(record[0x10]),
                "ic_rating": record[0x11],
                "ic_rating2": record[0x12],
                "ic_combo_id": signed_byte(record[0x13]),
            }

        systems.append(
            {
                "id": system_id,
                "map": list(data[map_offset : map_offset + MAP_CELLS]),
                "nodes": nodes,
            }
        )
    return systems


def file_class_labels(data: bytes) -> list[str]:
    """Read fixed-stride, FF-terminated node labels used by the ROM UI."""
    labels: list[str] = []
    require_range(
        data,
        FILE_CLASS_TABLE,
        FILE_CLASS_COUNT * FILE_CLASS_STRIDE,
        "Matrix file-class labels",
    )
    for class_id in range(FILE_CLASS_COUNT):
        start = FILE_CLASS_TABLE + class_id * FILE_CLASS_STRIDE
        record = data[start : start + FILE_CLASS_STRIDE]
        try:
            terminator = record.index(0xFF)
        except ValueError as error:
            raise ValueError(
                f"Matrix file-class label {class_id} is missing its FF terminator"
            ) from error
        labels.append(record[:terminator].decode("ascii"))
    return labels


def lua_file_class_catalog(labels: list[str]) -> str:
    """Render source labels as runtime-ready Lua strings with padding intact."""
    lines = [
        "-- Generated by tools/matrix_systems_extract.py from the US Genesis ROM.",
        "-- Fixed 16-byte records at ROM 0xE4060; preserve their source spacing.",
        "return {",
    ]
    for class_id, label in enumerate(labels):
        lines.append(f"  [{class_id}] = {json.dumps(label)},")
    lines.extend(["}", ""])
    return "\n".join(lines)


def fixed_text_records(
    data: bytes, start: int, count: int, stride: int, label: str
) -> list[str]:
    """Read fixed-width ROM text records terminated by the game's FF byte."""
    require_range(data, start, count * stride, label)
    records: list[str] = []
    for record_id in range(count):
        record = data[start + record_id * stride : start + (record_id + 1) * stride]
        try:
            terminator = record.index(0xFF)
        except ValueError as error:
            raise ValueError(
                f"{label} record {record_id} is missing its FF terminator"
            ) from error
        records.append(record[:terminator].decode("ascii"))
    return records


def matrix_hud_labels(data: bytes) -> dict[str, list[str] | list[int]]:
    """Extract the fixed Matrix traversal HUD labels and their rating columns."""
    return {
        "program_states": fixed_text_records(
            data, PROGRAM_STATE_TABLE, PROGRAM_STATE_COUNT,
            PROGRAM_STATE_STRIDE, "Matrix program-state labels"
        ),
        "alert_states": fixed_text_records(
            data, ALERT_STATE_TABLE, ALERT_STATE_COUNT,
            ALERT_STATE_STRIDE, "Matrix alert labels"
        ),
        "node_functions": fixed_text_records(
            data, NODE_FUNCTION_TABLE, NODE_FUNCTION_COUNT,
            NODE_FUNCTION_STRIDE, "Matrix node-function labels"
        ),
        "security_bands": fixed_text_records(
            data, SECURITY_BAND_TABLE, SECURITY_BAND_COUNT,
            SECURITY_BAND_STRIDE, "Matrix security-band labels"
        ),
        "ic_rating_columns": list(
            data[IC_RATING_COLUMN_TABLE : IC_RATING_COLUMN_TABLE + IC_TYPE_COUNT]
        ),
        "ic_types": fixed_text_records(
            data, IC_TYPE_TABLE, IC_TYPE_COUNT, IC_TYPE_STRIDE,
            "Matrix IC-type labels"
        ),
        "ic_visibility": fixed_text_records(
            data, IC_VISIBILITY_TABLE, IC_VISIBILITY_COUNT,
            IC_VISIBILITY_STRIDE, "Matrix IC-visibility labels"
        ),
    }


def lua_matrix_hud_catalog(tables: dict[str, list[str] | list[int]]) -> str:
    """Render ROM HUD text as zero-based Lua arrays with source padding intact."""
    lines = [
        "-- Generated by tools/matrix_systems_extract.py from the US Genesis ROM.",
        "-- Source tables: 0xE2FBE, 0xE3074, 0xE309E, 0xE30B6,",
        "-- 0xE30DE, 0xE30E7, and 0xE3177; preserve source spacing.",
        "return {",
    ]
    for name, values in tables.items():
        lines.append(f"  {name} = {{")
        for index, value in enumerate(values):
            rendered = json.dumps(value) if isinstance(value, str) else str(value)
            lines.append(f"    [{index}] = {rendered},")
        lines.append("  },")
    lines.extend(["}", ""])
    return "\n".join(lines)


def lua_catalog(systems: list[dict[str, object]]) -> str:
    """Render compact named records: one row per map row and node record."""
    lines = ["return {"]
    for system in systems:
        system_id = int(system["id"])
        map_cells = system["map"]
        nodes = system["nodes"]
        lines.extend(
            [
                f"  [{system_id}] = {{",
                f"    id = {system_id},",
                "    map = {",
            ]
        )
        for row in range(10):
            start = row * 14
            values = map_cells[start : start + 14]
            lines.append("      " + ", ".join(map(str, values)) + ",")
        lines.extend(["    },", "    nodes = {"])
        for node_id, node in nodes.items():
            links = ", ".join(str(node["links"][link]) for link in range(8))
            lines.append(
                f"      [{node_id}] = {{ function_id = {node['function_id']}, "
                f"file_class_id = {node['file_class_id']}, x = {node['x']}, "
                f"y = {node['y']}, security_color = {node['security_color']}, "
                f"security = {node['security']}, links = {{{links}}}, "
                f"ic_condition = {node['ic_condition']}, "
                f"ic_reaction = {node['ic_reaction']}, "
                f"ic_rating = {node['ic_rating']}, "
                f"ic_rating2 = {node['ic_rating2']}, "
                f"ic_combo_id = {node['ic_combo_id']} }},"
            )
        lines.extend(["    },", "  },"])
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rom",
        type=Path,
        default=Path("input/shadowrun_genesis_us.bin"),
        help="US Genesis ROM path (default: input/shadowrun_genesis_us.bin)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("gameplay/scripts/data/matrix_systems.lua"),
        help="generated Lua module path",
    )
    parser.add_argument(
        "--file-classes-output",
        type=Path,
        default=Path("gameplay/scripts/data/matrix_file_classes.lua"),
        help="generated Lua node-label module path",
    )
    parser.add_argument(
        "--hud-labels-output",
        type=Path,
        default=Path("gameplay/scripts/data/matrix_hud_labels.lua"),
        help="generated Lua Matrix HUD text module path",
    )
    args = parser.parse_args()

    rom = args.rom.read_bytes()
    systems = system_records(rom)
    labels = file_class_labels(rom)
    hud_labels = matrix_hud_labels(rom)
    node_count = sum(len(system["nodes"]) for system in systems)
    header = [
        "-- Generated by tools/matrix_systems_extract.py from the US Genesis ROM.",
        "-- System IDs and records follow the table at ROM 0x15DB48.",
        "-- The runtime consumes named fields and has no ROM-address dependency.",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "\n".join(header) + "\n" + lua_catalog(systems),
        encoding="utf-8",
        newline="\n",
    )
    args.file_classes_output.parent.mkdir(parents=True, exist_ok=True)
    args.file_classes_output.write_text(
        lua_file_class_catalog(labels),
        encoding="utf-8",
        newline="\n",
    )
    args.hud_labels_output.parent.mkdir(parents=True, exist_ok=True)
    args.hud_labels_output.write_text(
        lua_matrix_hud_catalog(hud_labels),
        encoding="utf-8",
        newline="\n",
    )
    print(
        f"systems={len(systems)} nodes={node_count} output={args.output}; "
        f"file_classes={len(labels)} output={args.file_classes_output}; "
        f"hud_tables={len(hud_labels)} output={args.hud_labels_output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
