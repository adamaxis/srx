#!/usr/bin/env python3
"""Offline extractor: ROM door/link data -> gameplay/scripts/data/world_links_data.lua.

Reads the US ROM only (no runtime decoding). Sources [C]:
  0x003232  56 scene profile pointers (long)
  profile+0x26  collision record list (5 BE words: x0,x1,y0,y1,code; ends at a
                word with the sign bit set). code bit 7 = link/event record,
                bits 6:5 = door row (0xBC52 rol.b #3 / and #3), bits 4:0 = event id.
  profile+0x4E  optional 32-byte event table: destination scene per event id
                (0x167AE). Null for scenes >= 0x0A.
  0x00BD34  return offsets per door row: lead, runner 2, runner 3 (dx,dy) (0xBC36)
  0x0009B8  same-map service return writes heading 0x8000 to all runners
  0x002E42/0x002E72/0x002ED2/0x002D92  cave room graph (doc 19 section 3)
Usage: extract_world_links.py [rom] [out.lua]
"""
import struct, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
rom_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "input", "shadowrun_genesis_us.bin")
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "gameplay", "scripts", "data", "world_links_data.lua")
d = open(rom_path, "rb").read()
L = lambda a: struct.unpack(">I", d[a:a + 4])[0]
W = lambda a: struct.unpack(">H", d[a:a + 2])[0]
S = lambda a: struct.unpack(">h", d[a:a + 2])[0]

SCENE_TABLE, SCENES = 0x3232, 56
RETURN_OFFSETS = 0xBD34
ROOM_SCENE, ROOM_NEXT, ROOM_ARRIVAL, ARRIVAL_XY = 0x2E42, 0x2E72, 0x2ED2, 0x2D92
ROOMS = 24

o = []
w = o.append
w("-- GENERATED by decompilation/ghidra_conversion/tools/rom_research/extract_world_links.py")
w("-- from the US ROM. Do not edit; re-run the tool. All values [C] ROM data.")
w("-- Sources: scene profiles 0x003232 (+0x26 collision records, +0x4E event table),")
w("-- return offsets 0x00BD34 (0xBC36), service return heading 0x0009B8,")
w("-- cave room graph 0x002E42/0x002E72/0x002ED2/0x002D92 (0x2CE0).")
w("-- Coordinates: record rects are inclusive map pixels; world units = px * 16.")
w("local M = {}")
w("")
w("M.source = { scene_table = 0x%06X, return_offsets = 0x%06X, service_return = 0x0009B8 }" % (SCENE_TABLE, RETURN_OFFSETS))
w("")
w("-- [row] = { lead, runner2, runner3 } world-unit offsets added to the lead's")
w("-- pre-step position at door contact (FFDF44..FFDF4E).")
w("M.return_offsets = {")
for row in range(4):
    a = RETURN_OFFSETS + row * 12
    trip = ", ".join("{ dx = %d, dy = %d }" % (S(a + 4 * i), S(a + 4 * i + 2)) for i in range(3))
    w("    [%d] = { %s },  -- 0x%06X" % (row, trip, a))
w("}")
w("")
w("-- 0x9B8: the same-map service return (d6 != 0) sets +0x2E/+0x34 = 0x8000.")
assert d[0x9B8:0x9C0] == bytes.fromhex("33fc800000ff012e"), "0x9B8 mismatch"
w("M.service_return_heading = 0x%04X" % W(0x9BA))
w("")
w("M.scenes = {")
links_total = 0
for s in range(SCENES):
    prof = L(SCENE_TABLE + 4 * s)
    recs = L(prof + 0x26)
    evt = L(prof + 0x4E)
    w("    [%d] = {  -- profile 0x%06X" % (s, prof))
    w("        records = 0x%06X," % recs)
    if evt:
        tbl = ", ".join("[%d] = %d" % (i, d[evt + i]) for i in range(32))
        w("        event_table_address = 0x%06X," % evt)
        w("        event_table = { %s }," % tbl)
    w("        links = {")
    a = recs; idx = 0
    while not (W(a) & 0x8000):
        x0, x1, y0, y1, code = (W(a + 2 * i) for i in range(5))
        if code & 0x80:
            w("            { record = 0x%06X, index = %d, x0 = %d, x1 = %d, y0 = %d, y1 = %d, code = 0x%02X }," % (a, idx, x0, x1, y0, y1, code))
            links_total += 1
        a += 10; idx += 1
    w("        },")
    w("    },")
w("}")
w("")
# Same-map service sites of the 0x1F5CA chain (doc 18 section 3): each
# handler is a chain of cmpi.b #scene,FFFBF8 / cmpi.b #zone,FFFBF9 tests.
SERVICE_HANDLERS = (("HOTEL", 0x1F65A, 0x1F830), ("HOSPITAL", 0x1F830, 0x1FA78), ("SHOP", 0x1FA78, 0x1FD80))
w("-- Same-map services (0x1F5CA chain). A matching (scene, event) is handled in")
w("-- place and returns d6 = FFFF: 0x9B8 heading + 0x2FA4 placement on close.")
w("M.services = {")
services = 0
for kind, a, b in SERVICE_HANDLERS:
    scene = None
    for p in range(a, b, 2):
        op = d[p:p + 2]; tgt = d[p + 4:p + 8]
        if op == b"\x0c\x39" and d[p + 2] == 0 and tgt == b"\x00\xff\xfb\xf8":
            scene = d[p + 3]
        elif op == b"\x0c\x39" and d[p + 2] == 0 and tgt == b"\x00\xff\xfb\xf9" and scene is not None:
            w("    { kind = \"%s\", scene = %d, event = %d, handler = 0x%06X }," % (kind, scene, d[p + 3], p))
            services += 1
w("}")
w("")
w("-- Cave/wilderness room graph (0x2CE0): room -> scene, exits by dir 0..3")
w("-- (zone codes 8..11) -> next room and arrival slot; arrival rows by scene.")
w("M.room_graph = {")
w("    scene = { %s }," % ", ".join("[%d] = %d" % (r, W(ROOM_SCENE + 2 * r)) for r in range(ROOMS)))
w("    next = {")
for r in range(ROOMS):
    w("        [%d] = { %s }," % (r, ", ".join("[%d] = %d" % (k, d[ROOM_NEXT + 4 * r + k]) for k in range(4))))
w("    },")
w("    arrival_slot = {")
for r in range(ROOMS):
    w("        [%d] = { %s }," % (r, ", ".join("[%d] = %d" % (k, d[ROOM_ARRIVAL + 4 * r + k]) for k in range(4))))
w("    },")
w("    -- row index: scene < 0x2C -> scene - 6, else scene - 0x2C + 4")
w("    arrival_xy = {")
for row in range(11):
    w("        [%d] = { %s }," % (row, ", ".join("[%d] = { x = %d, y = %d }" % (k, W(ARRIVAL_XY + row * 16 + 4 * k), W(ARRIVAL_XY + row * 16 + 4 * k + 2)) for k in range(4))))
w("    },")
w("}")
w("")
w("return M")
open(out_path, "w").write("\n".join(o) + "\n")
print("wrote", out_path, "link records", links_total, "services", services)
