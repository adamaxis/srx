#!/usr/bin/env python3
"""Offline importer: ROM doorway resources -> semantic Lua world data.

Reads the US ROM only (no runtime decoding). Sources [C]:
  0x003232  56 scene profile pointers (long)
  profile+0x26  collision record list (5 BE words: x0,x1,y0,y1,code; ends at a
                word with the sign bit set). The importer resolves each record
                into a spatial doorway and semantic transition; runtime Lua
                never sees the packed record or event selector.
  profile+0x4E  optional event destinations, joined to doorway transitions here.
  0x00BD34  return offsets per door row: lead, runner 2, runner 3 (dx,dy) (0xBC36)
  0x00167AE scene-mode bands; 0x0009B8 same-map services return facing south
  0x002E42/0x002E72/0x002ED2/0x002D92 cave rooms and arrival positions
Usage: extract_world_links.py [rom] [out.lua]
"""
import struct, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
rom_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "input", "shadowrun_genesis_us.bin")
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "gameplay", "scripts", "data", "world_links_data.lua")
d = open(rom_path, "rb").read()
L = lambda a: struct.unpack(">I", d[a:a + 4])[0]
W = lambda a: struct.unpack(">H", d[a:a + 2])[0]
S = lambda a: struct.unpack(">h", d[a:a + 2])[0]

SCENE_TABLE, SCENES = 0x3232, 56
RETURN_OFFSETS = 0xBD34
ROOM_SCENE, ROOM_NEXT, ROOM_ARRIVAL, ARRIVAL_XY = 0x2E42, 0x2E72, 0x2ED2, 0x2D92
ROOMS = 24
RETURN_SIDES = ("north", "east", "south", "west")
EXIT_DIRECTIONS = ("north", "east", "south", "west")
assert d[0x9B8:0x9C0] == bytes.fromhex("33fc800000ff012e"), "0x9B8 mismatch"

# Resolve same-map services during import. Their ROM scene/event comparisons
# are implementation details; gameplay data names the service itself.
SERVICE_HANDLERS = (("hotel", 0x1F65A, 0x1F830), ("hospital", 0x1F830, 0x1FA78), ("shop", 0x1FA78, 0x1FD80))
service_routes = {}
for kind, start, end in SERVICE_HANDLERS:
    scene = None
    for p in range(start, end, 2):
        op = d[p:p + 2]; target = d[p + 4:p + 8]
        if op == b"\x0c\x39" and d[p + 2] == 0 and target == b"\x00\xff\xfb\xf8":
            scene = d[p + 3]
        elif op == b"\x0c\x39" and d[p + 2] == 0 and target == b"\x00\xff\xfb\xf9" and scene is not None:
            service_routes[(scene, d[p + 3])] = kind

o = []
w = o.append
w("-- GENERATED by decompilation/ghidra_conversion/tools/rom_research/extract_world_links.py")
w("-- Offline-imported from the US ROM. Do not edit; re-run the importer.")
w("-- Provenance: profiles 0x003232; collision records at profile+0x26;")
w("-- event destinations at profile+0x4E; return formations 0x00BD34;")
w("-- scene modes 0x0167AE; same-map service return 0x0009B8;")
w("-- cave connections 0x002E42..0x002ED2;")
w("-- cave arrival positions 0x002D92. Runtime values below are semantic.")
w("local M = {}")
w("")
w("")
w("-- Door return formation by the side of the entrance. Coordinates are world-unit offsets.")
w("M.return_offsets = {")
for row in range(4):
    a = RETURN_OFFSETS + row * 12
    trip = ", ".join("{ x = %d, y = %d }" % (S(a + 4 * i), S(a + 4 * i + 2)) for i in range(3))
    w("    %s = { %s },  -- source row %d at 0x%06X" % (RETURN_SIDES[row], trip, row, a))
w("}")
w("")
w("M.scenes = {")
links_total = 0
for s in range(SCENES):
    prof = L(SCENE_TABLE + 4 * s)
    recs = L(prof + 0x26)
    evt = L(prof + 0x4E)
    mode = "street" if s < 0x15 else "building" if s < 0x2C else "cave" if s < 0x38 else None
    fields = []
    if mode is not None:
        fields.append("mode = %r" % mode)
    w("    [%d] = { %s, -- source profile 0x%06X" % (s, ", ".join(fields), prof))
    w("        links = {")
    a = recs; idx = 0
    while not (W(a) & 0x8000):
        x0, x1, y0, y1, code = (W(a + 2 * i) for i in range(5))
        if code & 0x80:
            side = RETURN_SIDES[(code >> 5) & 0x03]
            event_selector = code & 0x1F
            service = service_routes.get((s, event_selector))
            if service is not None:
                transition = "{ kind = 'same_map_service', service = %r }" % service
            elif evt:
                destination = d[evt + event_selector]
                if destination < 0x38:
                    transition = "{ kind = 'scene_change', destination_scene_id = %d }" % destination
                else:
                    transition = "{ kind = 'unresolved_destination' }"
            else:
                # Static destinations are absent for contextual field exits.
                transition = "{ kind = 'contextual_transition' }"
            bounds = (x0 * 16, (x1 + 1) * 16 - 1,
                      y0 * 16, (y1 + 1) * 16 - 1)
            w("            { bounds = { left = %d, right = %d, top = %d, bottom = %d }, return_side = %r, transition = %s }, -- source record 0x%06X" % (*bounds, side, transition, a))
            links_total += 1
        a += 10; idx += 1
    w("        },")
    w("    },")
w("}")
w("")
w("-- Cave rooms with named exits and resolved arrival positions.")
w("M.cave_rooms = {")
for room in range(ROOMS):
    w("    [%d] = { scene = %d, exits = {" % (room, W(ROOM_SCENE + 2 * room)))
    for direction_index, direction in enumerate(EXIT_DIRECTIONS):
        next_room = d[ROOM_NEXT + 4 * room + direction_index]
        arrival_slot = d[ROOM_ARRIVAL + 4 * room + direction_index]
        scene = W(ROOM_SCENE + 2 * next_room)
        arrival_row = scene - 6 if scene < 0x2C else scene - 0x2C + 4
        x = W(ARRIVAL_XY + arrival_row * 16 + arrival_slot * 4)
        y = W(ARRIVAL_XY + arrival_row * 16 + arrival_slot * 4 + 2)
        w("        %s = { room = %d, scene = %d, arrival = { x = %d, y = %d } }," % (direction, next_room, scene, x, y))
    w("    } },")
w("}")
w("")
w("return M")
with open(out_path, "w", newline="\n") as out:
    out.write("\n".join(o) + "\n")
print("wrote", out_path, "link records", links_total, "services", len(service_routes))
