const UsItemCatalog& us_item_catalog() {
    return kUsItems;
}

const UsSpecialItemModifierSelectorTable&
us_special_item_modifier_selector_table() {
    return kUsSpecialItemSelectors;
}

const UsItemDefinition* find_us_item_definition(
    const std::uint8_t item_code) {
    if (item_code == 0U || item_code > kUsItemDefinitionCount) {
        return nullptr;
    }
    return &kUsItems[static_cast<std::size_t>(item_code - 1U)];
}

const UsItemDefinition* find_us_item_definition(const UsItemCode item_code) {
    return find_us_item_definition(static_cast<std::uint8_t>(item_code));
}

