const UsItemCatalog& us_item_catalog() {
    return kUsItems;
}

const UsItemDefinition* find_us_item_definition(
    const std::uint8_t item_code) {
    if (item_code == 0U || item_code > kUsItemDefinitionCount) {
        return nullptr;
    }
    return &kUsItems[static_cast<std::size_t>(item_code - 1U)];
}

