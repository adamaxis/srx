-- menu/init.lua: registers every screen with the route and returns the route module.
local E = require("enums")
local Route = require("menu.route")
local S = E.MenuScreen
local legacy, wait_any = require("menu.screens.legacy"), require("menu.screens.wait_any")
local IA = require("menu.screens.item_action")
local CL = require("menu.screens.clips")
local AT = require("menu.screens.attributes")
local MG = require("menu.screens.magic")
local PS = require("menu.screens.pocket_secretary")
Route.register(S.COMMAND, require("menu.screens.command"))
Route.register(S.POSTURE, require("menu.screens.posture"))
Route.register(S.MESSAGE, require("menu.screens.message"))
Route.register(S.CYBERWARE, wait_any(E.MenuRegion.FULL))
Route.register(S.MAGICAL_DEFENSE, wait_any(E.MenuRegion.FULL))
Route.register(S.ITEM_ACTION, IA.ItemAction)
Route.register(S.DISCARD_CONFIRM, IA.Discard)
Route.register(S.INVENTORY_TRADE, IA.Trade)
Route.register(S.FIRST_AID, IA.FirstAid)
Route.register(S.CLIPS, CL.Clips)
Route.register(S.RELOAD_CONFIRM, CL.Confirm)
Route.register(S.CLIP_TRADE, CL.Trade)
Route.register(S.ATTRIBUTES_SKILLS, AT.Attributes)
Route.register(S.UPGRADE_PROMPT, AT.Prompt)
Route.register(S.MAGIC, MG.Magic)
Route.register(S.MAGIC_FORCE, MG.Force)
Route.register(S.MAGIC_POSTURE, MG.Posture)
Route.register(S.POCKET_SECRETARY, PS.PocketSecretary)
Route.register(S.NOTEBOOK, PS.Notebook)
Route.register(S.NOTEBOOK_TIPS, PS.Tips)
Route.register(S.MR_JOHNSONS, PS.Johnsons)
Route.register(S.DISMISS_RUNNER, PS.Dismiss)
local DBG = require("menu.screens.debug_menu")
Route.register(S.DEBUG_MENU, DBG.Debug)
Route.register(S.DEBUG_PICK_SYSTEM, DBG.Pick)
local SV, CD = require("menu.screens.save_load"), require("menu.screens.cyberdeck")
Route.register(S.SAVE_LOAD, SV.SaveLoad)
Route.register(S.SAVE_SLOT, SV.Slot)
Route.register(S.CYBERDECK, CD.Cyberdeck)
Route.register(S.PULL_PLUG, CD.PullPlug)
local DS = require("menu.screens.deck_screens")
Route.register(S.DECK_PROGRAM, DS.Program)
Route.register(S.DECK_CYBERINFO, DS.CyberInfo)
Route.register(S.DECK_STORAGE, DS.Storage)
Route.register(S.DECK_MAP, DS.Map)
return Route
