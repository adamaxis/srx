-- Generates records.hpp from gameplay/scripts/data. C++ only stores and looks
-- up typed content; behavior methods stay in Lua. Sources are noted in each
-- data module header.
local Items = require("data.items")
local Spells = require("data.spells")
local I, ItemOrder = Items.by_id, Items.catalog_order
local S, SpellOrder = Spells.by_id, Spells.catalog_order
local A = require("data.accessories").by_id
local P = require("data.actor_profiles").by_id
local o = {}
local function w(s) o[#o + 1] = s end
local function q(s) return string.format("%q", s) end
w("// GENERATED by gameplay/scripts/tools/gen_records_hpp.lua - do not edit.")
w("#pragma once\n#include <array>\n#include <cstdint>\n#include <optional>\n#include <stdexcept>\n#include <string_view>\n#include \"enums.hpp\"\nnamespace srx {")
w("struct ArmorModifiers { unsigned primary; unsigned secondary; };")
w("struct TargetMotionRange { unsigned minimum_distance; unsigned maximum_distance; };")
w("struct TotemSpellModifier { std::string_view spell_id; std::int16_t value; };")
w("struct Item { std::string_view id; std::string_view name; ItemKind kind; std::optional<std::uint32_t> purchase_base; TargetMotionRange target_motion_range; std::optional<ArmorModifiers> armor; std::array<TotemSpellModifier, 11> totem_modifiers; std::uint8_t totem_modifier_count; bool has_detail_art; };")
w("struct Spell { std::string_view id; std::string_view name; unsigned base_drain; unsigned force_drain_modifier; std::optional<TargetMotionRange> target_motion_range; };")
w("struct AccessoryRec { Accessory id; const char* name; uint32_t name_addr; std::array<uint16_t, 3> price_by_shop; };  // 0x1AAE07, 0x1AAE8C (0x58628)")
w("struct ActorProfile { const char* id; const char* package_id; int16_t sprite_type; const char* action_kind; uint8_t action_code; int16_t weapon; bool controls_movement, projectile, dynamic_encounter_only; };  // repo profiles")
w("inline constexpr std::array<Item, 50> kItems{{")
for _, id in ipairs(ItemOrder) do local r = I[id]
  local kind; for k, v in pairs(require("enums").ItemKind) do if v == r.kind then kind = k end end
  local price = r.purchase_base and string.format("%d", r.purchase_base) or "std::nullopt"
  local armor = r.armor and string.format(
    "ArmorModifiers{%d, %d}", r.armor.primary_modifier,
    r.armor.secondary_modifier) or "std::nullopt"
  local motion_range = string.format("TargetMotionRange{%d, %d}",
    r.target_motion_range.minimum_distance,
    r.target_motion_range.maximum_distance)
  local modifiers = {}
  for _, spell_id in ipairs(SpellOrder) do
    local value = r.totem_spell_modifiers and r.totem_spell_modifiers[spell_id]
    if value ~= nil then
      modifiers[#modifiers + 1] = string.format("{%s, %d}", q(spell_id), value)
    end
  end
  local modifier_count = #modifiers
  while #modifiers < 11 do modifiers[#modifiers + 1] = '{"", 0}' end
  w(string.format("  {%s, %s, ItemKind::%s, %s, %s, %s, {{%s}}, %d, %s},",
    q(r.id), q(r.name), kind, price, motion_range, armor,
    table.concat(modifiers, ", "), modifier_count,
    tostring(r.has_detail_art)))
end
w("}};\ninline constexpr std::array<Spell, 14> kSpells{{")
for _, id in ipairs(SpellOrder) do local s = S[id]
  local motion_range = s.target_motion_range and string.format(
    "TargetMotionRange{%d, %d}", s.target_motion_range.minimum_distance,
    s.target_motion_range.maximum_distance) or "std::nullopt"
  w(string.format("  {%s, %s, %d, %d, %s},",
    q(s.id), q(s.name), s.base_drain, s.force_drain_modifier, motion_range))
end
w("}};\ninline constexpr std::array<AccessoryRec, 6> kAccessories{{")
local AN = {}; for k, v in pairs(require("enums").Accessory) do AN[v] = k end
for i = 0, 5 do local a = A[i]
  w(string.format("  {Accessory::%s, %s, 0x%X, {%d, %d, %d}},", AN[i], q(a.name), a.name_addr, a.price_by_shop[0], a.price_by_shop[1], a.price_by_shop[2]))
end
local ids = {}; for k in pairs(P) do ids[#ids + 1] = k end; table.sort(ids)
w(string.format("}};\ninline constexpr std::array<ActorProfile, %d> kActorProfiles{{", #ids))
for _, k in ipairs(ids) do local p = P[k]
  w(string.format("  {%s, %s, %d, %s, %d, %d, %s, %s, %s},", q(p.id), p.package_id and q(p.package_id) or "nullptr", p.sprite_type or -1,
    q(p.action_kind), p.action_code or 0, p.weapon or -1, tostring(p.controls_movement), tostring(p.projectile), tostring(p.dynamic_encounter_only)))
end
w("}};")
w("inline const Item& item(std::string_view id) { for (const auto& entry : kItems) if (entry.id == id) return entry; throw std::out_of_range(\"unknown item id\"); }")
w("inline const Spell& spell(std::string_view id) { for (const auto& entry : kSpells) if (entry.id == id) return entry; throw std::out_of_range(\"unknown spell id\"); }")
w("inline const AccessoryRec& accessory(Accessory a) { return kAccessories.at(v(a)); }")
w("} // namespace srx")
print(table.concat(o, "\n"))
