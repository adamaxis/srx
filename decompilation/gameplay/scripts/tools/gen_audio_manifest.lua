-- Generates assets/audio/audio_manifest.tsv, the id-keyed audio resource
-- manifest the host mixer plays from (doc 26 §4.2). Run from gameplay/scripts:
--   lua5.4 tools/gen_audio_manifest.lua ../../assets > ../../assets/audio/audio_manifest.tsv
-- Inputs: enums.lua (E.MusicId / E.SoundId / E.MenuSound names), the asset
-- catalog resources.tsv (rendered aliases) and audio/loop-points.tsv.
package.path = "./?.lua;" .. package.path
local E = require("enums")
local root = assert(arg[1], "usage: gen_audio_manifest.lua <asset-root>")

local function read_tsv(path)
    local rows, header = {}, nil
    for line in io.lines(path) do
        line = line:gsub("\r$", "")
        if line ~= "" and line:sub(1, 1) ~= "#" then
            local fields = {}
            for field in (line .. "\t"):gmatch("([^\t]*)\t") do fields[#fields + 1] = field end
            if not header then header = fields else
                local row = {}
                for i, name in ipairs(header) do row[name] = fields[i] end
                rows[#rows + 1] = row
            end
        end
    end
    return rows
end

local catalog = {}
for _, row in ipairs(read_tsv(root .. "/resources.tsv")) do
    if row.kind == "audio" then catalog[row.alias] = row.path end
end
local loops = {}
for _, row in ipairs(read_tsv(root .. "/audio/loop-points.tsv")) do loops[row.alias] = row end

-- Table-2 resource index == sequence id (decimal suffix). Ids whose caller is
-- known were extracted under a semantic alias; 0x5C/0x5D play source-cadenced
-- composites of all ROM starts (assets/audio/README.md).
local semantic = {
    [0x10] = "audio.intro.title.stage-1", [0x12] = "audio.intro.title.stage-3",
    [0x16] = "audio.field.effect-016", [0x24] = "audio.menu.command-024",
    [0x29] = "audio.menu.command-029", [0x30] = "audio.field.world-effect-030",
    [0x5C] = "audio.intro.sega-logo-shock-sequence",
    [0x5D] = "audio.intro.shadowrun-logo-reveal-sequence",
}
-- Rendered streams with no proven end (doc 26 §4.4): play until stopped.
local persistent = { [0x05] = true, [0x0C] = true, [0x0D] = true, [0x0E] = true,
                     [0x0F] = true, [0x28] = true, [0x30] = true }

local function name_for(id)
    for _, group in ipairs({ { "MusicId", E.MusicId }, { "SoundId", E.SoundId }, { "MenuSound", E.MenuSound } }) do
        local best
        for k, v in pairs(group[2]) do
            if v == id and (best == nil or k < best) then best = k end
        end
        if best then return group[1] .. "." .. best end
    end
    return nil
end
local music = {}
for _, v in pairs(E.MusicId) do music[v] = true end

local out = { "# GENERATED by gameplay/scripts/tools/gen_audio_manifest.lua; do not edit.",
              "id\tenum_name\tkind\talias\tloop_start\tloop_end\tpersistent" }
local missing = {}
for id = 0x00, 0x5D do
    local alias = semantic[id]
    if not alias then
        local suffix = string.format("%03d", id)
        alias = catalog["audio.music.resource." .. suffix] and ("audio.music.resource." .. suffix)
             or catalog["audio.effects.resource." .. suffix] and ("audio.effects.resource." .. suffix)
    end
    if alias and catalog[alias] then
        local name = name_for(id)
        if not name then missing[#missing + 1] = string.format("0x%02X", id) end
        local loop = loops[alias]
        out[#out + 1] = table.concat({
            string.format("0x%02X", id), name or "-", music[id] and "music" or "sfx", alias,
            loop and loop.loop_start_frame or "-", loop and loop.loop_end_frame or "-",
            persistent[id] and "1" or "0" }, "\t")
    end
end
if #missing > 0 then
    io.stderr:write("ids without an enum name: " .. table.concat(missing, " ") .. "\n")
    os.exit(1)
end
print(table.concat(out, "\n"))
