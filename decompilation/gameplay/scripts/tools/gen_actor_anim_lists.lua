-- Regenerates data/actor_anim_lists.lua from the ROM animation-list table 0x62AC
-- (read by the animator 0x600E). Usage: lua tools/gen_actor_anim_lists.lua <rom.bin> > data/actor_anim_lists.lua
local rom = assert(io.open(assert(arg[1], "rom path"), "rb")):read("a")
local function W(a) return (string.unpack(">I2", rom, a + 1)) end
local function L(a) return (string.unpack(">I4", rom, a + 1)) end
local E = require("enums")
local ActorVisualProfile = E.ActorVisualProfile
local SoundId = E.SoundId
-- Source pose-list offsets used only by this offline ROM importer.
local SourcePose = {
    IDLE = 0x00, WALK = 0x20, ITEM = 0x40, HURT = 0x60,
    SPELL = 0x80, WEAPON = 0xA0, ACTION = 0xC0,
    SPELL_DEATH_E0 = 0xE0, SPELL_DEATH_E4 = 0xE4, DEATH = 0xE8,
}
local POSES = {
    { "idle", "IDLE", SourcePose.IDLE },
    { "walk", "WALK", SourcePose.WALK },
    { "item_action", "ITEM", SourcePose.ITEM },
    { "hurt", "HURT", SourcePose.HURT },
    { "spell", "SPELL", SourcePose.SPELL },
    { "weapon", "WEAPON", SourcePose.WEAPON },
    { "action", "ACTION", SourcePose.ACTION },
    { "spell_death_e0", "SPELL_DEATH_E0", SourcePose.SPELL_DEATH_E0 },
    { "spell_death_e4", "SPELL_DEATH_E4", SourcePose.SPELL_DEATH_E4 },
    { "death", "DEATH", SourcePose.DEATH },
}
-- Resolve the ROM's actor +0x0E list selector while importing animation
-- assets. Runtime Lua consumes these stable profile IDs only.
local VISUAL_PROFILE_BY_SOURCE_KIND = {
    [1] = ActorVisualProfile.HIT_SPARK,
    [3] = ActorVisualProfile.FIELD_RUNNER,
    [4] = ActorVisualProfile.ORK_BANDERSNATCH,
    [5] = ActorVisualProfile.HUMAN_GUARD,
    [6] = ActorVisualProfile.ELVEN_MAGE,
    [7] = ActorVisualProfile.GHOUL_EYE_FIVER,
    [8] = ActorVisualProfile.YAKUZA_WEENR,
    [9] = ActorVisualProfile.VAMPIRE_GATOR_SHAMAN,
    [10] = ActorVisualProfile.LONE_STAR_MAGE,
    [11] = ActorVisualProfile.PEDESTRIAN_RAT_SHAMAN,
    [12] = ActorVisualProfile.HELL_HOUND,
    [13] = ActorVisualProfile.GARGOYLE,
    [14] = ActorVisualProfile.WENDIGO,
    [15] = ActorVisualProfile.THON,
}
local AUDIO_EVENT_NAME_BY_VALUE = {
    [0x2E] = "DAC_SAMPLE_2E", [0x2F] = "DAC_SAMPLE_2F",
    [0x40] = "DAC_SAMPLE_40", [0x41] = "DAC_SAMPLE_41",
    [0x42] = "DAC_SAMPLE_42", [0x45] = "DAC_SAMPLE_45",
    [0x46] = "DAC_SAMPLE_46", [0x47] = "DAC_SAMPLE_47",
    [0x4F] = "DAC_SAMPLE_4F", [0x56] = "DAC_SAMPLE_56",
    [0x57] = "DAC_SAMPLE_57", [0x58] = "DAC_SAMPLE_58",
    [0x59] = "DAC_SAMPLE_59", [0x5A] = "DAC_SAMPLE_5A",
}
local HURT_AUDIO_TABLE = 0xB03E -- 0xB07E indexes this by actor +0x0E [C].
local DOWN_AUDIO_TABLE = 0xB05E -- 0xB340 indexes this by actor +0x0E [C].
local out = {}
local function p(s) out[#out + 1] = s end
p("-- data/actor_anim_lists.lua: named host clips converted from ROM 0x62AC [C].")
p("-- Lists expose frame count, loop behavior, and finite-clip duration in actor animation updates.")
p("-- The importer converts source rate fields; they are not runtime animation state.")
p("-- Every direction agrees unless `by_dir` is present. E0/E4 are single lists.")
p("-- B07E indexes B03E at 0xB086..0xB096; B330 indexes B05E at 0xB340..0xB350 [C].")
p("-- Generated by tools/gen_actor_anim_lists.lua from rom.bin; regenerate rather than hand-edit.")
p('local SoundId = require("enums").SoundId')
p("return {")
for kind = 3, 15 do
    local visual_profile = assert(
        VISUAL_PROFILE_BY_SOURCE_KIND[kind],
        "unmapped actor animation profile: " .. tostring(kind))
    local pt = L(0x62AC + kind * 4)
    p(string.format('    ["%s"] = {  -- table 0x%X', visual_profile, pt))
    for _, pose in ipairs(POSES) do
        local clip_id, name, base = pose[1], pose[2], pose[3]
        local dirs = (base == SourcePose.SPELL_DEATH_E0 or
                      base == SourcePose.SPELL_DEATH_E4) and 1 or 8
        local rows, same = {}, true
        for d = 0, dirs - 1 do
            local lp = L(pt + base + d * 4)
            local hdr = W(lp)
            rows[d + 1] = { finite = hdr >= 0x8000, count = hdr & 0x7FFF, rate = W(lp + 2), at = lp }
            if d > 0 and (rows[d + 1].finite ~= rows[1].finite or rows[d + 1].count ~= rows[1].count or
                          rows[d + 1].rate ~= rows[1].rate) then same = false end
        end
        local r = rows[1]
        local line = string.format(
            '        ["%s"] = { looping = %s, frame_count = %d',
            clip_id, tostring(not r.finite), r.count)
        if r.finite then
            assert(r.rate > 0, "finite clip has no source frame rate")
            line = line .. string.format(
                ", frame_duration_updates = %.8g", 0x1000 / r.rate)
        end
        if not same then
            local t = {}
            for d, x in ipairs(rows) do
                local variant = string.format(
                    "{ looping = %s, frame_count = %d",
                    tostring(not x.finite), x.count)
                if x.finite then
                    assert(x.rate > 0, "finite clip has no source frame rate")
                    variant = variant .. string.format(
                        ", frame_duration_updates = %.8g",
                        0x1000 / x.rate)
                end
                t[d] = variant .. " }"
            end
            line = line .. ", by_dir = { " .. table.concat(t, ", ") .. " }"
        end
        p(line .. string.format(" },  -- %s list 0x%X", name, r.at))
    end
    p("    },")
end
-- Kind 1 (player hit spark, ActorVisualProfile.HIT_SPARK) only ever runs the
-- selector 0xB2BC installs in child +0x16 (E.HitSpark.SELECTOR) [C].
do
    local kind, base = 1, E.HitSpark.SELECTOR
    local visual_profile = assert(VISUAL_PROFILE_BY_SOURCE_KIND[kind])
    local pt = L(0x62AC + kind * 4)
    local lp = L(pt + base)
    local hdr = W(lp)
    p(string.format('    ["%s"] = {  -- table 0x%X', visual_profile, pt))
    local finite = hdr >= 0x8000
    local count = hdr & 0x7FFF
    local rate = W(lp + 2)
    assert(finite and rate > 0, "hit-spark clip must be finite and timed")
    p(string.format(
        '        ["hit_spark"] = { looping = false, frame_count = %d, frame_duration_updates = %.8g },  -- HIT_SPARK list 0x%X',
        count, 0x1000 / rate, lp))
    p("    },")
end
p("    audio = {")
for _, audio in ipairs({
    { "hurt_by_visual_profile", HURT_AUDIO_TABLE },
    { "down_by_visual_profile", DOWN_AUDIO_TABLE },
}) do
    local name, offset = audio[1], audio[2]
    p("        " .. name .. " = {")
    for kind = 1, 15 do
        local visual_profile = VISUAL_PROFILE_BY_SOURCE_KIND[kind]
        if visual_profile ~= nil then
            local sound_id = W(offset + kind * 2)
            local sound_name = assert(
                AUDIO_EVENT_NAME_BY_VALUE[sound_id],
                string.format("unmapped actor audio event 0x%X", sound_id))
            p(string.format('            ["%s"] = SoundId.%s,',
                visual_profile, sound_name))
        end
    end
    p("        },")
end
p("    },")
p("}")
io.write(table.concat(out, "\n"), "\n")
