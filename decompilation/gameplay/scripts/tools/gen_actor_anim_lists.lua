-- Regenerates data/actor_anim_lists.lua from the ROM animation-list table 0x62AC
-- (read by the animator 0x600E). Usage: lua tools/gen_actor_anim_lists.lua <rom.bin> > data/actor_anim_lists.lua
local rom = assert(io.open(assert(arg[1], "rom path"), "rb")):read("a")
local function W(a) return (string.unpack(">I2", rom, a + 1)) end
local function L(a) return (string.unpack(">I4", rom, a + 1)) end
local POSES = { {"IDLE", 0x00}, {"WALK", 0x20}, {"ITEM", 0x40}, {"HURT", 0x60}, {"SPELL", 0x80},
                {"WEAPON", 0xA0}, {"ACTION", 0xC0}, {"SPELL_DEATH_E0", 0xE0}, {"SPELL_DEATH_E4", 0xE4},
                {"DEATH", 0xE8} }
local out = {}
local function p(s) out[#out + 1] = s end
p("-- data/actor_anim_lists.lua: ROM 0x62AC[kind] -> pose lists read by 0x600E [C].")
p("-- Per kind (3..15) and pose base: finite (hdr bit15), count (hdr & 0x7FFF), rate (+2 word;")
p("-- looping lists ignore it and use 0x6092's +0xCA speed rate). Every direction agrees unless")
p("-- `by_dir` is present. E0/E4 are single lists (0xB0AC/0xB0E4 do not add a direction).")
p("-- Generated by tools/gen_actor_anim_lists.lua from rom.bin; regenerate rather than hand-edit.")
p("return {")
for kind = 3, 15 do
    local pt = L(0x62AC + kind * 4)
    p(string.format("    [%d] = {  -- table 0x%X", kind, pt))
    for _, pose in ipairs(POSES) do
        local name, base = pose[1], pose[2]
        local dirs = (base == 0xE0 or base == 0xE4) and 1 or 8
        local rows, same = {}, true
        for d = 0, dirs - 1 do
            local lp = L(pt + base + d * 4)
            local hdr = W(lp)
            rows[d + 1] = { finite = hdr >= 0x8000, count = hdr & 0x7FFF, rate = W(lp + 2), at = lp }
            if d > 0 and (rows[d + 1].finite ~= rows[1].finite or rows[d + 1].count ~= rows[1].count or
                          rows[d + 1].rate ~= rows[1].rate) then same = false end
        end
        local r = rows[1]
        local line = string.format("        [0x%02X] = { finite = %s, count = %d, rate = 0x%X", base,
            tostring(r.finite), r.count, r.rate)
        if not same then
            local t = {}
            for d, x in ipairs(rows) do
                t[d] = string.format("{ finite = %s, count = %d, rate = 0x%X }", tostring(x.finite), x.count, x.rate)
            end
            line = line .. ", by_dir = { " .. table.concat(t, ", ") .. " }"
        end
        p(line .. string.format(" },  -- %s list 0x%X", name, r.at))
    end
    p("    },")
end
p("}")
io.write(table.concat(out, "\n"), "\n")
