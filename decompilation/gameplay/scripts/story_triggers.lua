-- The 0x53A78 field trigger table (0x15FD5C, 23 long entries). Indices whose
-- entry is 0x49A0 (a bare rts) are no-ops; the rest are the live triggers.
-- All values below are read from the ROM [C]; tests_lua/story_flags_tests.lua
-- re-derives every field from decompilation/input/shadowrun_genesis_us.bin.
--
--   handler   entry address in the table
--   roots     dialogue nodes the handler loads into a0 before 0x1F246
--             (control-flow reachable from the entry, jsr targets excluded)
--   commands  every 0x12CCB4 command id reachable from those roots (node
--             format of the 0x1F3C4 prompt loop; command continuations that
--             load a0 are followed). Generated by shadowrun/tools/
--             story_trigger_commands.py.
--   tail      jsr 0x2196C sites in the handler after its conversation: they
--             mark whatever FFDD64 holds when the conversation returns.
--   preset    { site, index } pairs where the handler itself loads FFDD64
--             with an immediate and calls 0x2196C (branch-dependent, before
--             the conversation). Only trigger 21 has them.
local StoryTriggers = {}

StoryTriggers.TABLE = 0x15FD5C
StoryTriggers.COUNT = 23            -- 0x53A8A: cmpi.w #$16,d0 / bgt
StoryTriggers.EMPTY_HANDLER = 0x49A0

StoryTriggers.LIVE = {
