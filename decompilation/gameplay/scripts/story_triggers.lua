function StoryTriggers.is_live(index)
    return math.type(index) == "integer" and StoryTriggers.LIVE[index] ~= nil
end

-- Sorted live indices.
function StoryTriggers.live_indices()
    local out = {}
    for index in pairs(StoryTriggers.LIVE) do out[#out + 1] = index end
    table.sort(out)
    return out
end

-- Reachable commands of `index` that reach 0x2196C (per `marks`, normally
-- StoryFlags.DIALOGUE_COMMAND_MARKS).
function StoryTriggers.story_commands(index, marks)
    local out = {}
    for _, command in ipairs(StoryTriggers.LIVE[index].commands) do
        if marks[command] ~= nil then out[#out + 1] = command end
    end
    return out
end

return StoryTriggers
