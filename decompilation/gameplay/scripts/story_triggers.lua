             commands = { 0x05, 0x06, 0x21, 0x22, 0x30, 0x31 } },
    [1]  = { handler = 0x53B16, roots = { 0xF49E8 },
             commands = { 0x06, 0x13, 0x14, 0x16, 0x20, 0x4B, 0x4C } },
    [2]  = { handler = 0x53B78, roots = { 0xF4B68 },
